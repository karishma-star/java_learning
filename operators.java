public class operators{
    public static void main(String[] args){
        int a=1;
        int b=2;
        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);
        System.out.println(a%b);
        System.out.println(a==b);
        System.out.println(a!=b);
        System.out.println(a>=b);
        //ternary operator
        System.out.println(a>b ? "a is greater" : "b is greater");
    }
}